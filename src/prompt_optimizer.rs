    /// Generate a simple unique-ish ID for tests (not a real UUID).
    fn uuid_stub() -> String {
        use std::sync::atomic::{AtomicU64, Ordering};
        static COUNTER: AtomicU64 = AtomicU64::new(0);
        format!("test-{}", COUNTER.fetch_add(1, Ordering::Relaxed))
    }

    #[test]
    fn test_optimization_config_defaults() {
        let config = OptimizationConfig::default();
        assert_eq!(config.min_trajectories, 10);
        assert_eq!(config.variants_to_generate, 3);
        assert_eq!(config.good_threshold, 4);
        assert_eq!(config.bad_threshold, 2);
    }

    #[test]
    fn test_insufficient_data() {
        let rt = tokio::runtime::Runtime::new().unwrap();
        rt.block_on(async {
            let optimizer = PromptOptimizer::default();
            // Only 3 trajectories, need 10
            let trajectories: Vec<TrajectoryEntry> = (0..3)
                .map(|i| make_trajectory(&format!("prompt {}", i), "output", Some(3), true))
                .collect();

            // We cannot call optimize_phase without a real LlmRouter, but we can
            // verify the insufficient data check directly by simulating.
            assert!(trajectories.len() < optimizer.config.min_trajectories);

            // Verify the result type we'd get
            let result = OptimizationResult::InsufficientData {
                available: trajectories.len(),
                needed: optimizer.config.min_trajectories,
            };
            match result {
                OptimizationResult::InsufficientData { available, needed } => {
                    assert_eq!(available, 3);
                    assert_eq!(needed, 10);
                }
                _ => panic!("Expected InsufficientData"),
            }
        });
    }

    #[test]
    fn test_estimate_current_score() {
        // Mix of scored and unscored trajectories
        let trajectories = vec![
            make_trajectory("p1", "o1", Some(5), true),
            make_trajectory("p2", "o2", Some(3), true),
            make_trajectory("p3", "o3", None, true),    // no score — should be ignored
            make_trajectory("p4", "o4", Some(4), true),
            make_trajectory("p5", "o5", Some(2), false),
        ];

        let score = PromptOptimizer::estimate_current_score(&trajectories);
        // (5 + 3 + 4 + 2) / 4 = 3.5
        assert!((score - 3.5).abs() < f64::EPSILON);
    }

    #[test]
    fn test_estimate_current_score_no_scores() {
        let trajectories = vec![
            make_trajectory("p1", "o1", None, true),
            make_trajectory("p2", "o2", None, true),
        ];
        let score = PromptOptimizer::estimate_current_score(&trajectories);
        assert!((score - 0.0).abs() < f64::EPSILON);
    }

    #[test]
    fn test_estimate_current_score_empty() {
        let score = PromptOptimizer::estimate_current_score(&[]);
        assert!((score - 0.0).abs() < f64::EPSILON);
    }

    #[test]
    fn test_split_trajectories() {
        let trajectories = vec![
            make_trajectory("good1", "excellent output", Some(5), true),
            make_trajectory("good2", "great output", Some(4), true),
            make_trajectory("mid1", "ok output", Some(3), true),
            make_trajectory("bad1", "poor output", Some(2), false),
            make_trajectory("bad2", "terrible output", Some(1), false),
            make_trajectory("unscored", "no score", None, true),
        ];

        let (good, bad) = split_trajectories(&trajectories, 4, 2);

        // Good: score >= 4 → "good1" (5) and "good2" (4)
        assert_eq!(good.len(), 2);
        assert_eq!(good[0].0, "good1");
        assert_eq!(good[1].0, "good2");

        // Bad: score <= 2 → "bad1" (2) and "bad2" (1)
        assert_eq!(bad.len(), 2);
        assert_eq!(bad[0].0, "bad1");
        assert_eq!(bad[1].0, "bad2");
    }

